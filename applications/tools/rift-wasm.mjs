// Vendors the rift builder (TitanRO/client dlls/rift-wasm) into src/Core/Rift/riftWasm.js as Base64.
//
//   node applications/tools/rift-wasm.mjs <rift_wasm.wasm> <TitanRO/client commit it was built from>
//
// Build the .wasm in a TitanRO/client checkout at that commit (see dlls/rift-wasm/Dockerfile):
//   cd dlls/rift-wasm && docker build -t rift-wasm-build -f Dockerfile . &&
//   docker run --rm -u "$(id -u):$(id -g)" -e HOME=/tmp -v "$PWD/..":/w -w /w/rift-wasm rift-wasm-build \
//     cargo build --release --target wasm32-unknown-unknown
// The client's genmap must be the commit the map server's genmap plugin builds, or the cells won't match.
import fs from 'node:fs';

const [wasmPath, commit] = process.argv.slice(2);
if (!wasmPath || !/^[0-9a-f]{7,40}$/.test(commit || '')) {
	console.error('usage: node applications/tools/rift-wasm.mjs <rift_wasm.wasm> <client commit>');
	process.exit(2);
}
const bytes = fs.readFileSync(wasmPath);
const mod = new WebAssembly.Module(bytes);
const names = WebAssembly.Module.exports(mod).map(e => e.name);
for (const need of [
	'memory',
	'rw_alloc',
	'rw_free',
	'rw_plan',
	'rw_source',
	'rw_build',
	'rw_file',
	'rw_file_len',
	'rw_out',
	'rw_out_len',
	'rw_clear'
]) {
	if (!names.includes(need)) {
		console.error(`${wasmPath} has no ${need}: not dlls/rift-wasm's build?`);
		process.exit(1);
	}
}
if (WebAssembly.Module.imports(mod).length) {
	console.error(`${wasmPath} has imports; Core/Rift instantiates it with none`);
	process.exit(1);
}
const b64 = bytes.toString('base64');
const js = [
	'/**',
	' * Core/Rift/riftWasm.js',
	' *',
	` * The rift builder, TitanRO/client dlls/rift-wasm at ${commit} (${bytes.length} bytes), as Base64.`,
	' * Generated by applications/tools/rift-wasm.mjs; do not edit.',
	' */',
	'',
	`export const RIFT_WASM_SOURCE = '${commit}';`,
	'',
	'// prettier-ignore',
	`export const RIFT_WASM = '${b64}';`,
	''
].join('\r\n');
fs.writeFileSync('src/Core/Rift/riftWasm.js', js);
console.log(`src/Core/Rift/riftWasm.js: ${bytes.length} bytes from client ${commit}`);
